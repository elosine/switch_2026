#!/usr/bin/env node
// tuplet_bands.js — THE CONVERSION for the tuplet pass of Section 3 (his word 2026-11-14, SW-46): a time container names a BAND (slow ·
// medium · fast, in strikes per second); a player's single strikes inside it become tuplets; this chart says, for the player's pulse at
// that moment, WHICH tuplet of the ladder lands in the band. Writes docs/TUPLET_BANDS.md from the numbers below — change them here.
//
//   node tools/tuplet_bands.js            # rewrite the doc
//   node tools/tuplet_bands.js --pick 83 fast     # one answer: the step for a pulse of 83 bpm in the fast band
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const CEILING = 10;                                   // strikes per second, never above (his word 2026-11-14: "the max tempo be 10 a second")
const BANDS = { slow: [1, 3], medium: [3, 6], fast: [6, CEILING] };   // strikes per second [low, high) — PROPOSED, his word pending (SW-46)
// the ladder (SW-45): n strikes in one beat, and n (odd) strikes in the space of two beats — the value is strikes per beat
const LADDER = [
  [1, '1 per beat (the strike itself)'], [1.5, '3 in 2 beats'], [2, 'eighths (2 per beat)'], [2.5, '5 in 2 beats'], [3, 'triplets (3 per beat)'],
  [3.5, '7 in 2 beats'], [4, 'sixteenths (4 per beat)'], [4.5, '9 in 2 beats'], [5, 'quintuplets (5 per beat)'], [5.5, '11 in 2 beats'],
  [6, 'sextuplets (6 per beat)'], [7, 'septuplets (7 per beat)'], [8, 'thirty-seconds (8 per beat)'],
];
// the pulses the section holds (bank/phase_form.json + the workshop's sets): the unisons, the drifts' tops, every swarm tempo
const PULSES = [53.6, 57.7, 62.5, 68, 72.7, 75, 78, 80, 83.3, 85.7, 90, 92.3, 93.8, 100, 107.1, 109.1, 110.6, 120, 133.3];
const rate = (step, bpm) => step * bpm / 60;
const inBand = (r, b) => r >= BANDS[b][0] && r < BANDS[b][1] && r <= CEILING;
// the step for a pulse and a band: inside the band, nearest the band's geometric middle; if none lands inside, the nearest step to the band
function pick(bpm, band) {
  const [lo, hi] = BANDS[band], mid = Math.sqrt(lo * Math.min(hi, CEILING));
  const inside = LADDER.filter(([s]) => inBand(rate(s, bpm), band));
  const pool = inside.length ? inside : LADDER.filter(([s]) => rate(s, bpm) <= CEILING);
  const best = pool.reduce((a, b) => Math.abs(Math.log(rate(b[0], bpm) / mid)) < Math.abs(Math.log(rate(a[0], bpm) / mid)) ? b : a);
  return { step: best[0], name: best[1], perSecond: +rate(best[0], bpm).toFixed(2), inside: inside.length > 0, choices: inside.map(([s]) => s) };
}
const ai = process.argv.indexOf('--pick');
if (ai > 0) { const r = pick(+process.argv[ai + 1], process.argv[ai + 2] || 'medium'); console.log(JSON.stringify(r)); process.exit(0); }

const f1 = n => (Math.round(n * 10) / 10).toString();
const lines = [];
lines.push('# TUPLET BANDS — the conversion for Section 3\'s tuplet pass');
lines.push('');
lines.push('> Generated by `tools/tuplet_bands.js` (' + new Date().toISOString().slice(0, 10) + ') — change the numbers THERE, then re-run. His words: `docs/COMPOSITION_NOTES.md` SW-45 · SW-46.');
lines.push('');
lines.push('## The rule, in four lines');
lines.push('');
lines.push('- **A time container names a band** — slow · medium · fast — in STRIKES PER SECOND. Inside it, a player\'s single strikes of the phase form become tuplets.');
lines.push('- **The player\'s beat is the gap to its next strike** (the phase form\'s pulse at that moment: 54 … 133 bpm, drifting and gliding). The tuplet divides that gap.');
lines.push('- **The step chosen is the one of the ladder whose rate (strikes per beat × pulse ÷ 60) lands inside the band**, nearest the band\'s middle; if none lands inside at that pulse, the nearest step to the band.');
lines.push('- **Never above ' + CEILING + ' strikes a second** (his ceiling, 2026-11-14).');
lines.push('');
lines.push('## The bands (proposed — his word pending)');
lines.push('');
lines.push('| band | strikes per second |');
lines.push('|---|---|');
for (const b of Object.keys(BANDS)) lines.push('| ' + b + ' | ' + BANDS[b][0] + ' … ' + BANDS[b][1] + ' |');
lines.push('');
lines.push('## The ladder (SW-45) — strikes per beat');
lines.push('');
lines.push(LADDER.map(([s, n]) => '`' + s + '` ' + n).join(' · '));
lines.push('');
lines.push('## The chart — for a player\'s pulse, the step in each band');
lines.push('');
lines.push('The cell is the step (strikes per beat) and, in brackets, the strikes per second it gives. An italic cell is the nearest step when none lands inside the band at that pulse. The last column is the first step over the ceiling.');
lines.push('');
lines.push('| pulse bpm | strike = | slow ' + BANDS.slow.join('…') + ' | medium ' + BANDS.medium.join('…') + ' | fast ' + BANDS.fast.join('…') + ' | over ' + CEILING + '/s from |');
lines.push('|---|---|---|---|---|---|');
for (const bpm of PULSES) {
  const cells = Object.keys(BANDS).map(b => { const p = pick(bpm, b); const t = p.step + ' (' + f1(p.perSecond) + '/s)'; return p.inside ? t + (p.choices.length > 1 ? ' · also ' + p.choices.filter(s => s !== p.step).join(' ') : '') : '*' + t + '*'; });
  const over = LADDER.find(([s]) => rate(s, bpm) > CEILING);
  lines.push('| ' + bpm + ' | ' + f1(bpm / 60) + '/s | ' + cells.join(' | ') + ' | ' + (over ? over[0] + ' (' + f1(rate(over[0], bpm)) + '/s)' : '—') + ' |');
}
lines.push('');
lines.push('## How a container is applied (for the AI that builds the pass)');
lines.push('');
lines.push('1. The containers are a list he gives: start (score s) · length (s) · band — e.g. `1 s slow · 3 s medium · 2 s fast`, in whatever order he says; they tile a stretch of 277.8 … 480.');
lines.push('2. For every phase-form note (`properties.phaseForm.player · hit`) whose time falls in a container: its beat = the time to that player\'s next strike; its pulse = 60 ÷ beat; the step = this chart\'s pick for the container\'s band; the note becomes `step` strikes spread evenly over the beat (a `k in 2 beats` step spans two gaps: the pair of strikes becomes k even strikes).');
lines.push('3. The share of strikes that become tuplets may grow through a container or a run of them (SW-44: "3 single strikes and a tuplet, then the singles diminish") — the share is a second dial, not the band\'s.');
lines.push('4. During a glide the pulse moves strike by strike, so the pick may change inside one container — that is the acceleration he described, not a fault.');
lines.push('5. `node tools/tuplet_bands.js --pick <bpm> <band>` gives one answer with the alternatives that also land inside.');
lines.push('');
fs.writeFileSync(path.join(ROOT, 'docs', 'TUPLET_BANDS.md'), lines.join('\n') + '\n');
console.log('docs/TUPLET_BANDS.md · ' + PULSES.length + ' pulses × ' + Object.keys(BANDS).length + ' bands · ceiling ' + CEILING + '/s');
