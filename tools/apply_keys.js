#!/usr/bin/env node
// apply_keys.js — THE MEASURED KEYS of the by-key voices (PLAN 1d, 2026-11-10; RUNNING_LOG §146): the keys a `kind: "key"` voice actually
// sounds on, read by tools/key_sweep.js (the meter, through Reaper's virtual keyboard), written into sandbox/instruments.js as a generated
// block, MEASURED_KEYS, applied at load by applyMeasuredKeys(): the voice's `keys: "pending"` becomes a table [{ midi, label }] and its range
// the span of those keys — what tools/artic_deal.js deals a by-key voice onto (its nearest key) and what the strikes drawer can list.
// Mirrors tools/apply_ranges.js and apply_bend_ranges.js. Re-run after every key sweep.
//
//   bank/measured_keys.json: { "violin": { "pizz_behind_bridge_vel": { "keys": [55, 57, …], "when": "…", "how": "key_sweep …" } }, … }
//   node tools/apply_keys.js [--in bank/measured_keys.json] [--dry]
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 && args[i + 1] != null ? args[i + 1] : d; };
const IN = path.resolve(ROOT, opt('in', 'bank/measured_keys.json')), RECIPE = path.join(ROOT, 'sandbox', 'instruments.js');
const M = JSON.parse(fs.readFileSync(IN, 'utf8'));
const BEGIN = '// ---- MEASURED KEYS (generated by tools/apply_keys.js — do not edit by hand) ----', END = '// ---- end of the measured keys ----';
const lines = ['const MEASURED_KEYS = {   // the keys a by-key voice sounds on, read by tools/key_sweep.js; bank/measured_keys.json is the source'];
let n = 0;
for (const [inst, voices] of Object.entries(M)) {
    if (inst.startsWith('_')) continue;
    lines.push('  ' + inst + ': {');
    for (const [key, d] of Object.entries(voices)) { lines.push('    ' + JSON.stringify(key) + ': ' + JSON.stringify(d.keys) + ',' + (d.when ? '   // ' + d.when + (d.how ? ' · ' + d.how : '') : '')); n++; }
    lines.push('  },');
}
lines.push('};');
lines.push('function applyMeasuredKeys(all, measured) {   // a by-key voice gets its measured key table and the span of those keys as its range');
lines.push('  for (const [inst, voices] of Object.entries(measured || {})) {');
lines.push('    const I = all[inst]; if (!I) continue;');
lines.push('    for (const [key, ks] of Object.entries(voices)) { const q = I.techniques.find((t) => t.key === key); if (!q || !ks || !ks.length) continue;');
lines.push('      q.keys = ks.map((m) => ({ midi: m, label: "key " + m + " (measured)" })); q.rangeLow = Math.min(...ks); q.rangeHigh = Math.max(...ks); q.keysMeasured = true; }');
lines.push('  }');
lines.push('}');
lines.push('applyMeasuredKeys(INSTRUMENTS, MEASURED_KEYS);');
const block = BEGIN + '\n' + lines.join('\n') + '\n' + END + '\n';
let src = fs.readFileSync(RECIPE, 'utf8');
const a = src.indexOf(BEGIN), b = src.indexOf(END);
if (a >= 0 && b > a) src = src.slice(0, a) + block + src.slice(b + END.length + 1);
else { const anchor = '// ---- end of the measured bend ranges ----\n'; const i = src.indexOf(anchor); if (i < 0) { console.error('no anchor (the measured bend block) in the recipe'); process.exit(1); } src = src.slice(0, i + anchor.length) + '\n' + block + src.slice(i + anchor.length); }
if (args.includes('--dry')) { console.log(block); process.exit(0); }
fs.writeFileSync(RECIPE, src);
console.log(n + ' by-key voice(s) given their measured keys in sandbox/instruments.js');
